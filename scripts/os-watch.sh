#!/usr/bin/env bash
# scripts/os-watch.sh — session-scoped event watcher (dumb poller). Wake-up system v2, see
# docs/wake-loop-v2-design.md §7。
#
# Usage: bash scripts/os-watch.sh <session_id> [team_id]
#   (started by the Leader in the ACTIVE state with run_in_background: ... &)
#
# Semantics:
#   - Polls GET /api/wake/actionable (zero SQL in bash; the criteria are centralized in the API)
#   - Benign signals self-absorb (agent still running / run not in a terminal state → keep sleeping)
#   - Only exits on actionable (an agent finished / a run reached a terminal state / a new memo), relying on the harness's "a background task
#     exiting re-invokes the model" to wake the Leader (batch0 verified this mechanism exists)
#   - 1h hard timeout against zombies; session-scoped (dies with the session process), never a resident component
#   - At runtime maintains wake-state/<sid>.armed (so the turn-end guard can tell "watcher armed"),
#     cleared on exit (trap) — guard and watcher each own separate files, no read-modify-write race
#
# Exit codes: 0=actionable hit / 2=API unreachable / 3=hard timeout
set -uo pipefail

SID="${1:?usage: os-watch.sh <session_id> [team_id]}"
TID="${2:-}"
POLL="${OS_WATCH_POLL:-8}"            # Poll interval, seconds
MAX_LIFETIME="${OS_WATCH_MAX:-3600}"  # Hard timeout 1h, against zombies

STATE_DIR="$HOME/.claude/data/ai-team-os/wake-state"
SAFE_SID="$(printf '%s' "$SID" | tr -c 'A-Za-z0-9._-' '_')"
ARMED_FILE="$STATE_DIR/${SAFE_SID}.armed"
PORT="$(cat "$HOME/.claude/data/ai-team-os/api_port.txt" 2>/dev/null || echo 8000)"
BASE="${AITEAM_API_URL:-http://localhost:${PORT}}"
mkdir -p "$STATE_DIR"

# Time convention: UTC, and **with a +00:00 offset** — after the whole DB unified on UTC, watermark strings are self-describing, and the two ends no longer rely on
# their own conventions to align. The first SINCE is generated by this script; afterwards, always reuse the watermark returned by the API.
SINCE="$(date -u +%Y-%m-%dT%H:%M:%S+00:00)"
START="$(date +%s)"

cleanup() { rm -f "$ARMED_FILE"; }
# EXIT only cleans up; INT/TERM clean up and exit (otherwise the loop would continue after the trap and the process would not die with the signal).
trap cleanup EXIT
trap 'cleanup; exit 143' INT TERM

# Heartbeat armed marker = now + 2*poll (does not expire within a sleep interval; if the watcher dies unexpectedly it auto-expires after ~2*poll)
arm() { echo "$(( $(date +%s) + 2 * POLL ))" > "$ARMED_FILE"; }

QS="session_id=${SID}"
[ -n "$TID" ] && QS="${QS}&team_id=${TID}"

while :; do
  arm
  if (( $(date +%s) - START >= MAX_LIFETIME )); then
    echo "WATCHER_TIMEOUT reached max lifetime ${MAX_LIFETIME}s, exiting; Leader please re-check whether any work is still in flight"
    exit 3
  fi
  if ! RESP="$(curl -fsS --max-time 3 "${BASE}/api/wake/actionable?${QS}&since=${SINCE}" 2>/dev/null)"; then
    echo "WATCHER_API_UNREACHABLE endpoint unreachable, exiting and leaving it to /loop as fallback"
    exit 2
  fi
  if printf '%s' "$RESP" | grep -q '"actionable"[[:space:]]*:[[:space:]]*true'; then
    echo "ACTIONABLE ${RESP}"
    exit 0
  fi
  # Benign: roll the watermark (monotonic water level, the same event is not reported twice), keep sleeping
  NEW_SINCE="$(printf '%s' "$RESP" | sed -n 's/.*"watermark"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p')"
  [ -n "$NEW_SINCE" ] && SINCE="$NEW_SINCE"
  echo "STATUS benign next=${POLL}s"
  sleep "$POLL"
done
